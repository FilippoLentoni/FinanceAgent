"""Portable reads of the exact pinned XNYS artifact shipped by FinancialPlanning.

The artifact is generated by FinancialPlanning/scripts/generate_calendar.py from
exchange_calendars 4.13.2. It is copied byte-for-byte, never a guessed holiday list.
Regenerate/copy and update the digest together when extending calendar coverage.
"""
from __future__ import annotations

import hashlib
import json
from datetime import UTC, date, datetime, time, timedelta
from functools import lru_cache
from pathlib import Path
from zoneinfo import ZoneInfo

ARTIFACT = Path(__file__).resolve().parents[1] / 'data/calendars/xnys-exchange_calendars-4.13.2-20100101-20271231.json'
ARTIFACT_SHA256 = 'bd684a5bd685e15dd40f424ea5ad9dd23d84b460883f198d01cb5efc3ed74078'


@lru_cache(maxsize=1)
def calendar() -> dict:
    raw = ARTIFACT.read_bytes()
    if hashlib.sha256(raw).hexdigest() != ARTIFACT_SHA256:
        raise ValueError('pinned XNYS calendar checksum differs')
    document = json.loads(raw)
    if document.get('exchange') != 'XNYS' or document.get('synthetic'):
        raise ValueError('a real pinned XNYS calendar is required')
    return document


def session(day: date) -> dict:
    document = calendar()
    if not document['coverage']['start'] <= day.isoformat() <= document['coverage']['end']:
        raise ValueError('date outside pinned XNYS calendar coverage')
    if day.weekday() >= 5:
        return {'status': 'weekend'}
    row = document['days'][day.isoformat()]
    return {'status': row} if isinstance(row, str) else row


def close_utc(day: date) -> datetime:
    document, row = calendar(), session(day)
    if row['status'] not in ('regular', 'early_close'):
        raise ValueError('closed exchange date has no session close')
    closing = time.fromisoformat(row.get('close') or document['regular_close'])
    return datetime.combine(day, closing, tzinfo=ZoneInfo(document['timezone'])).astimezone(UTC)


def evidence(at: datetime) -> dict:
    if at.tzinfo is None:
        raise ValueError('exchange time must include a timezone')
    document = calendar()
    day = at.astimezone(ZoneInfo(document['timezone'])).date()
    row = session(day)
    latest = day
    while session(latest)['status'] not in ('regular', 'early_close') or close_utc(latest) > at:
        latest -= timedelta(days=1)
    return {'calendar_version': document['version'], 'calendar_checksum': 'sha256:' + ARTIFACT_SHA256,
            'session_status': row['status'], 'expected_completed_session': latest.isoformat(),
            'is_trading_session': row['status'] in ('regular', 'early_close')}


def research_collection_open(at: datetime) -> bool:
    if at.tzinfo is None:
        raise ValueError('exchange time must include a timezone')
    local = at.astimezone(ZoneInfo(calendar()['timezone']))
    row = session(local.date())
    return (row['status'] in ('regular', 'early_close') and local.time() >= time(8, 45)
            and at < close_utc(local.date()))
